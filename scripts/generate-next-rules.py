#!/usr/bin/env python3
"""Generate ordinary-rule tables from resolved Shogitter rules, in priority order."""
import argparse
import collections
import json
from pathlib import Path

RULES = {
    111: (2, 'Narazu', 'narazu'), 138: (2, 'NifuAri', 'nifu-ari'),
    46: (3, 'ShoKyoLeft', 'sho-kyo-left'), 47: (3, 'ShoKyoRight', 'sho-kyo-right'),
    65: (3, 'Nakodo', 'nakodo'), 147: (3, 'QueenKing', 'queen-king'),
    30: (4, 'TorazuGin', 'torazu-gin'), 31: (4, 'AiTorazuGin', 'ai-torazu-gin'),
    153: (4, 'Zarikani', 'zarikani'), 165: (4, 'ZarikaniTonbo', 'zarikani-tonbo'),
    79: (5, 'Semai', 'semai'), 90: (5, 'Semmai', 'semmai'), 91: (5, 'Hiroi', 'hiroi'),
    17: (6, 'Dobutsu', 'dobutsu'), 28: (7, 'Toruichi', 'toruichi'),
    92: (8, 'Hisha', 'hisha'), 103: (8, 'Kaku', 'kaku'),
    22: (12, 'Shishio', 'shishio'), 117: (12, 'HonoShishi', 'hono-shishi'), 163: (13, 'Nigyoku', 'nigyoku'),
    88: (9, 'Totsugeki', 'totsugeki'), 21: (10, 'AiHappokei', 'ai-happokei'), 20: (10, 'Happokei', 'happokei'),
    112: (11, 'Patrol', 'patrol'), 113: (11, 'Lortap', 'lortap'),
    159: (8, 'Seireigi', 'seireigi'), 44: (8, 'KyoLeft', 'kyo-left'), 45: (8, 'KyoRight', 'kyo-right'),
}
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('input', type=Path)
p.add_argument('--through', type=int, default=13)
p.add_argument('--web', type=Path, required=True)
a = p.parse_args()
root = Path(__file__).resolve().parents[1]
text = ['// Generated by scripts/generate-next-rules.py from resolved Shogitter definitions.', 'use super::*;']
manifest = []
fmt = lambda xy: '&[' + ','.join('(' + ','.join(map(str, v)) + ')' for v in xy) + ']'
for q in json.loads(a.input.read_text()):
    rid = q['ruleId']; priority, cls, name = RULES[rid]
    if priority > a.through: continue
    rule = q['rule']; w, h = rule['size']; bases = list(rule['nari'])
    entries = list(dict.fromkeys(bases + [v for v in rule['nari'].values() if v]))
    defs = {d['species']: d for d in q['pieces']}; ix = {v: i for i, v in enumerate(entries)}
    base = {v: v for v in bases}
    for source, target in rule['nari'].items():
        if target:
            assert target not in base, (rid, target)
            base[target] = source
    inv = collections.Counter(c[1] for f in q['initial']['ban'] for c in f if c)
    prefix = cls.upper()
    text += [f'#[cfg(feature = "{name}")]', f'const {prefix}_PIECES: &[PieceDef] = &[']
    for id in entries:
        d = defs[id]; steps = []; rays = []
        for move in d['move']:
            if rid == 88 and move['move'][1] > 0: continue
            assert move['type'] in [1, 2, 8], (rid, id, move)
            (steps if move['type'] in [1,8] else rays).append(move['move'])
        dead = next((y for y in range(h) if any(0 <= w//2+dx < w and 0 <= y+dy < h for dx,dy in steps+rays)), h)
        promotion = rule['nari'].get(id)
        promo = f'Some(PieceId({ix[promotion]}))' if promotion else 'None'
        value = {'aa':100,'ab':300,'ac':300,'ad':450,'ae':550,'af':750,'ag':900,'ah':2500,'bg':100,'bh':500,'bi':400,'bj':2500}.get(id, 350+80*len(rays)+20*len(steps))
        text.append(f'piece!("{id}", {fmt(steps)}, {fmt(rays)}, {promo}, {bases.index(base[id])}, {str(id in rule["winkoma"]).lower()}, {dead}, {value}),')
    text += ['];', f'#[cfg(feature = "{name}")]', f'const {prefix}_INITIAL: &[([u16;2], &str, u8)] = &[']
    for x, file in enumerate(q['initial']['ban']):
        for y, c in enumerate(file):
            if c: text.append(f'([{x+1},{y+1}], "{c[1]}", {c[0]}),')
    text += ['];', f'#[cfg(feature = "{name}")]', f'ordinary_rule!({cls}, {rid}, "{name}", {w}, {h}, {prefix}_PIECES, {prefix}_INITIAL, &[{",".join(str(inv[b]) for b in bases)}], {('NoHands' if rid==103 else 'Hands<'+str(len(entries))+'>')}, {1 if rid==17 else 3});']
    manifest.append({'ruleId':rid,'name':name,'width':w,'height':h,'royals':rule['winkoma'],'useHands':rid != 103,'lion':rid in [22,117],'pieces':[{'id':id} for id in entries],'handIds':bases})
root.joinpath('haitaka/src/extended/classical/ordinary_defs.rs').write_text('\n'.join(text)+'\n')
a.web.joinpath('app/engines/ordinaryRules.ts').write_text('// Generated by generate-next-rules.py.\nexport const ORDINARY_RULES = '+json.dumps(manifest,ensure_ascii=False,indent=2)+' as const;\n')
